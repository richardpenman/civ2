/*
 * The HD graphics' picture decoder (src/platform/hd_image.c,
 * hd_decode_image): a lossy WebP, a lossless WebP with alpha, a PNG with
 * alpha, and what is neither, through the one helper.  The WebPs were made
 * with cwebp 1.5.0 (docs/HD-GRAPHICS.md):
 *
 *   lossy.webp: a 16x8 gradient, R = x*16, G = y*32, B = 128;
 *               cwebp -q 90 -m 4 -sharp_yuv
 *   alpha.webp: 8x8, R = 255 left / 0 right, G = 0 top / 255 bottom,
 *               B = 64, A = 255 where x+y is even, else x*32;
 *               cwebp -lossless -exact
 *   anim_webp: an animated WebP, 6 frames of 8x8, frame i a 2x2 square
 *               at (i, i/2), colour (40i, 255-40i, 64), alpha 255 on its
 *               diagonal, 128 off it, transparent elsewhere; img2webp
 *               -loop 0 -kmax 3 -kmin 2 -lossless -exact (sub-frames,
 *               a disposal to the background, key frames 1 and 4)
 *
 * and the own heralds' table (hd_herald_parse).
 *
 * Run by make test:
 *   cc -O2 -DHAVE_CONFIG_H -Isrc/third_party/libwebp -o build/hd_image_test \
 *     tests/hd_image_test.c src/platform/hd_image.c \
 *     src/third_party/libwebp/src/{dec,demux,dsp,utils}/[a-z]*.c -lm && build/hd_image_test
 */
