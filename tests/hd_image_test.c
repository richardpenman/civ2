static int failed;

static void check(int ok, const char *what)
{
    if (!ok) {
        printf("FAILED: %s\n", what);
        failed = 1;
    }
}

int main(void)
{
    unsigned char *p;
    int w, h, x, y, worst = 0;

    p = hd_decode_image(lossy_webp, sizeof lossy_webp, &w, &h);
    check(p && w == 16 && h == 8, "lossy WebP: 16x8");
    if (p && w == 16 && h == 8)
        for (y = 0; y < h; y++)
            for (x = 0; x < w; x++) {
                const unsigned char *q = p + (y * w + x) * 4;
                int want[4] = {x * 16, y * 32, 128, 255}, i;
                for (i = 0; i < 4; i++)
                    if (abs(q[i] - want[i]) > worst)
                        worst = abs(q[i] - want[i]);
            }
    check(worst <= 16, "lossy WebP: within 16 of the original");
    free(p);

    p = hd_decode_image(alpha_webp, sizeof alpha_webp, &w, &h);
    check(p && w == 8 && h == 8, "lossless WebP: 8x8");
    if (p && w == 8 && h == 8)
        for (y = 0; y < h; y++)
            for (x = 0; x < w; x++) {
                const unsigned char *q = p + (y * w + x) * 4;
                if (q[0] != (x < 4 ? 255 : 0) || q[1] != (y < 4 ? 0 : 255) || q[2] != 64 ||
                    q[3] != ((x + y) % 2 == 0 ? 255 : x * 32)) {
                    check(0, "lossless WebP with alpha: exact");
                    x = y = 8;
                }
            }
    free(p);

    p = hd_decode_image(rgba_png, sizeof rgba_png, &w, &h);
    check(p && w == 2 && h == 2 && p[0] == 255 && p[3] == 255 && p[5] == 255 && p[7] == 128 && p[10] == 255 &&
          p[11] == 0 && p[12] == 255 && p[15] == 255, "PNG with alpha");
    free(p);

    {
        /* the animation's frames in any order: from a key frame, or on from the last */
        static const int order[] = {5, 0, 3, 4, 2, 1, 1, 5, 4};
        unsigned char *copy = malloc(sizeof anim_webp);
        HdAnim *a;
        int k, ok = 1;
        memcpy(copy, anim_webp, sizeof anim_webp);
        a = hd_anim_open(copy, sizeof anim_webp);
        hd_anim_size(a, &w, &h);
        check(a && hd_anim_frames(a) == 6 && w == 8 && h == 8, "animated WebP: 6 frames of 8x8");
        for (k = 0; a && k < (int)(sizeof order / sizeof *order); k++) {
            int i = order[k];
            const unsigned char *f = hd_anim_frame(a, i);
            for (y = 0; f && y < 8; y++)
                for (x = 0; x < 8; x++) {
                    const unsigned char *q = f + (y * 8 + x) * 4;
                    int in = x >= i && x < i + 2 && y >= i / 2 && y < i / 2 + 2;
                    int al = in ? ((x - i + y - i / 2) % 2 == 0 ? 255 : 128) : 0;
                    if (q[3] != al || (al && (q[0] != i * 40 || q[1] != 255 - i * 40 || q[2] != 64)))
                        ok = 0;
                }
            if (!f)
                ok = 0;
        }
        check(ok, "animated WebP: each frame composited exactly, in any order");
        check(!hd_anim_frame(a, 6) && !hd_anim_frame(a, -1), "animated WebP: no frame 6");
        hd_anim_close(a);
        copy = malloc(16);
        memcpy(copy, "RIFF\x08\0\0\0WEBPVP8 ", 16);
        check(!hd_anim_open(copy, 16), "animated WebP: a bad one NULL");
    }
    {
        HdHerald hh;
        check(hd_herald_parse("rus 92 64 219 416 12 0 89 90 131 132 179 180 227 228 275 herald-RUS.webp\n", &hh) &&
              !strcmp(hh.code, "RUS") && hh.x == 92 && hh.y == 64 && hh.w == 219 && hh.h == 416 && hh.fps == 12 &&
              hh.seg[0][0] == 0 && hh.seg[0][1] == 89 && hh.seg[1][0] == 90 && hh.seg[4][1] == 275 &&
              !strcmp(hh.file, "herald-RUS.webp"), "heralds.txt: a line");
        check(!hd_herald_parse("RUS 92 64 219 416 12 0 89 90 131 132 179 180 227 228 herald-RUS.webp", &hh),
              "heralds.txt: a segment short");
        check(!hd_herald_parse("RUS 92 64 219 416 12 0 89 90 131 132 179 180 227 300 275 x.webp", &hh),
              "heralds.txt: a segment backwards");
        check(!hd_herald_parse("# comment", &hh), "heralds.txt: a comment");
    }
    check(!hd_decode_image((const unsigned char *)"GIF89a......", 12, &w, &h), "neither: NULL");
    check(!hd_decode_image(lossy_webp, 40, &w, &h), "a cut WebP: NULL");
    printf(failed ? "hd_image_test FAILED (lossy WebP within %d)\n" : "hd_image_test passed (lossy WebP within %d)\n", worst);
    return failed;
}
